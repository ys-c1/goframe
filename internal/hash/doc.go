// Package hash 提供状态指纹：全量指纹与逐位等价的增量指纹。
//
// # 为什么换掉了逐字 XOR 链
//
// 原来的指纹是逐字 FNV-1a 链：h ← (h ^ w) * prime。XOR 与进位的相互作用使
// 这一步既不是模 2^64 的加法同态，也不能按块复合，因此无法把某个实体的
// 贡献单独缓存、单独替换——改一个槽位会让整条链之后的每一步都变。要做到
// “只重算脏槽位、结果仍与全量逐位相同”，指纹必须对槽位是可分解的。
//
// 本包保留同样的 FNV 常量（offset、prime）与“按固定顺序混合”的语义，
// 把混合从 XOR 改为加法，得到严格可分解的定义。
//
// # 指纹定义
//
// 记 n 为实体数，p = 1099511628211，o = 14695981039346656037，P = p^4
// （模 2^64 运算，以下省略 mod）。实体 i 的四个 32 位字依次为
// posX、posY、velX、velY，记作 x_{i,0..3}。
//
// 槽位摘要（只依赖该实体自己的数据与下标）：
//
//	seed_i  = o + i * p
//	D_i     = fold(seed_i, x_{i,0}, x_{i,1}, x_{i,2}, x_{i,3})
//	fold(h, y…) : 对每个字 h ← (h + y) * p
//
// 槽位权重（只依赖下标与 n）：
//
//	W_i = p * P^(n-1-i)
//
// 帧号项：
//
//	Q(t) = p * P^n * (o + t)
//
// 全量指纹（每次从状态重算）：
//
//	Full(t, S) = Q(t) + Σ_{i=0}^{n-1} W_i * D_i(S_i)
//
// 权重使指纹对实体顺序敏感；D_i 里的 seed_i 使同一组数值落在不同实体上
// 也得到不同贡献。
//
// # 增量定义
//
// 增量算法缓存每个槽位的 D_i 以及部分和
//
//	Sum = Σ_i W_i * D_i,   Value = Q(t) + Sum
//
// 若实体 i 的数值变为 x'，只需
//
//	D_i ← D_i(x'),   Sum ← Sum + W_i * (D_i(x') - D_i(x))
//
// 其余槽位一字不动。Q(t) 由 SetTick 用预计算的系数 O(1) 更新。
//
// # 等价条件
//
// 一次状态更新只影响被更新实体自己的槽位。设第 t 帧状态为 S_t、更新映射
// 为 U_t，条件为：
//
//	(C) 若 U_t 只写实体 i，则 S_{t+1}[j] = S_t[j] 对所有 j ≠ i。
//
// sim 以结构保证 (C)：Push 只写 velX[i]、velY[i]；Integrate 的循环体只读
// 实体 i 自己的四个值、只写实体 i 自己的四个值，实体之间没有读写交叉。
// 另外 State 只在数值确实变化时标脏，所以“实际变化的槽位”必然被标脏；
// 多标脏无害（重算后 D_i 不变，增量加零）。
//
// # 定理（逐位等价）
//
// 设在 (C) 成立、且每个变化槽位都被标脏的前提下，增量初始值由 Full 的同一
// 组 D_i 建立，则对任意帧 t：
//
//	Incremental.Value() == Full(tick_t, S_t)   （64 位逐位相等）
//
// 证明（对帧数归纳）：
//
//	 基础：t = 0 时 D_i 由 S_0 算出，Sum = Σ W_i D_i，Q(tick_0) 精确，
//	 故 Value = Full(tick_0, S_0)。
//
//	 归纳：设第 t 帧结束时 Value = Full(tick_t, S_t)。第 t+1 帧中所有实际
//	 变化的槽位都在脏集合里。Update 对每个脏槽位 k 把缓存的 D_k 换成
//	 S_{t+1} 对应的值，并给 Sum 加上 W_k * (D_k(S_{t+1}) - D_k(S_t))；
//	 未变的槽位 k 即使被多标脏，增量也是 D_k - D_k = 0。于是
//
//		Sum_{t+1} = Σ_k W_k D_k(S_{t+1}),
//
//	 与全量求和式逐项相同；加法在模 2^64 下可交换、可结合，求和顺序无关。
//	 SetTick 把 Q 同步到 tick_{t+1}。故 Value = Full(tick_{t+1}, S_{t+1})。
//	 归纳完成。∎
//
// 注意证明没有用到任何概率论证：增量维护的是与全量完全相同的整数，而不是
// “以高概率相同”的摘要。
//
// # 不满足条件时会漏掉跨项影响
//
// 反例：更新改动了实体 j 的数值，却没有把 j 标脏（例如绕过 State 方法直接
// 写内存，或一个把位移写进别的实体槽位的耦合更新）。此时 j 不在脏集合里，
// 增量不会重算 D_j，Value 中仍是 W_j * D_j(S_t)；全量用的是 D_j(S_{t+1})。
// 两者之差恰为
//
//	Full - Value = W_j * (D_j(S_{t+1}) - D_j(S_t))   （mod 2^64）
//
// 错误只落在 j 这一项上，其他槽位看不出任何异常——这正是“漏掉跨项影响”：
// 它不会自我暴露，只能靠逐位对拍发现。
//
// 单个 32 位字的改动一定被检出：fold 对字是仿射的，第 r 个字改 δ 使
// ΔD_j = p^(4-r) * δ。W_j = p * P^(n-1-j)，p 为奇数，故 W_j * ΔD_j 为
// 奇数倍的 δ；0 < |δ| < 2^32，奇数倍的 δ 不可能被 2^64 整除，差非零。
// 多个槽位同时改动则可能发生模 2^64 的抵消，但那是与全量指纹本身的碰撞
// 同一级别的问题，不影响“哪些槽位被改、就在哪些槽位上验证”的结论。
